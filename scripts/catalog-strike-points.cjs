// Derive contact landmarks from the exact isolated game sprites, without altering PNGs.
const fs=require('node:fs'),path=require('node:path');
const {createCanvas,Image}=require('@napi-rs/canvas');
const {harness}=require('./gameplay-harness.cjs');
const root=path.resolve(__dirname,'..');
class LocalImage extends Image{set src(v){super.src=path.resolve(root,v.split('?')[0]);}get src(){return super.src;}}
(async()=>{
 const h=harness(1,{art:true,globals:{Image:LocalImage,setTimeout,fetch:async v=>({ok:true,json:async()=>JSON.parse(fs.readFileSync(path.resolve(root,v.split('?')[0])))})},document:{createElement:()=>createCanvas(1,1)}});
 await h.s.DrawnAnimation.loading;if(h.s.DrawnAnimation.status!=='ready')throw Error('Sprite loading failed');
 const points={};
 for(const def of h.s.CHARACTERS){points[def.id]={};
  for(const clip of ['jab','heavy','kick','lowKick','airPunch','airKick','rise','rush']){
   const rows=[];
   for(let index=0;index<(['airPunch','airKick','rise','rush'].includes(clip)?4:8);index++){
    const f=h.s.DrawnAnimation.sprite(def.id,clip,index);
    const pixels=f.canvas.getContext('2d').getImageData(0,0,f.canvas.width,f.canvas.height);
    let max=-Infinity,list=[];
    // Restrict to the striking limb: don't mistake a planted toe or flying hair for a fist.
    const band=clip==='lowKick'?[-14,1]:clip==='kick'?[-42,-10]:clip==='airKick'?[-65,-8]:clip==='airPunch'?[-65,-18]:clip==='rise'?[-60,-25]:[-46,-23];
    for(let y=0;y<pixels.height;y++)for(let x=0;x<pixels.width;x++){
     const ly=f.y+y/2,lx=f.x+x/2;
     if(ly<band[0]||ly>band[1]||pixels.data[(y*pixels.width+x)*4+3]<160)continue;
     if(lx>max){max=lx;list=[ly];}else if(lx===max)list.push(ly);
    }
    list.sort((a,b)=>a-b);if(!list.length)throw Error('Missing limb');
    rows.push([max,list[Math.floor(list.length/2)]]);
   }
   points[def.id][clip]=rows;
  }
 }
 fs.writeFileSync(path.resolve(root,'js/strike-art.js'),'// Contact landmarks in sprite-local pixels; generated by catalog-strike-points.cjs.\nwindow.STRIKE_ART='+JSON.stringify(points)+';\n');
 console.log(JSON.stringify({characters:Object.keys(points),points:Object.values(points).reduce((n,c)=>n+Object.values(c).reduce((n,p)=>n+p.length,0),0)}));
})().catch(e=>{console.error(e);process.exitCode=1;});
